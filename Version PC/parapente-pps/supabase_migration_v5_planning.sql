-- Migration v5 : planning des journées (journées > ateliers > épreuves)
-- ============================================================
-- À exécuter UNE SEULE FOIS dans Supabase (SQL Editor -> New query -> coller -> Run),
-- avant de synchroniser pour la première fois depuis la version 0.5 de l'application.
-- Le script peut être relancé sans risque (il ne recrée ni ne vide rien d'existant).
--
-- Sans ce script, la synchronisation continue de fonctionner pour tout le reste (pilotes,
-- épreuves, résultats...) mais affiche un avertissement : le planning n'est pas synchronisé.
--
-- Principe (identique aux autres tables) : "uuid" = identifiant commun à tous les appareils,
-- "updated_at" = sert à savoir quelle version d'une ligne est la plus récente.
-- Les horaires (heure_debut / heure_fin) sont stockés en texte "HH:mm", comme dans l'application.
-- ============================================================

-- ---------- Journées ----------
create table if not exists public.journees (
    id            bigint generated by default as identity primary key,
    uuid          uuid not null unique default gen_random_uuid(),
    nom           text not null,
    date_journee  date,
    ordre         integer not null default 0,
    updated_at    timestamptz not null default now()
);

-- ---------- Ateliers (rattachés à une journée) ----------
create table if not exists public.ateliers (
    id            bigint generated by default as identity primary key,
    uuid          uuid not null unique default gen_random_uuid(),
    journee_id    bigint not null references public.journees(id) on delete cascade,
    nom           text not null,
    creneau       text not null default 'MATIN' check (creneau in ('MATIN', 'APRES_MIDI')),
    heure_debut   text,
    heure_fin     text,
    lieu          text,
    responsable   text,
    ordre         integer not null default 0,
    updated_at    timestamptz not null default now()
);

create index if not exists ateliers_journee_idx on public.ateliers (journee_id);

-- ---------- Épreuves d'un atelier (une épreuve = un seul atelier) ----------
-- "ordre" = ordre de passage dans l'atelier.
create table if not exists public.atelier_epreuves (
    id            bigint generated by default as identity primary key,
    atelier_id    bigint not null references public.ateliers(id) on delete cascade,
    epreuve_id    bigint not null references public.epreuves(id) on delete cascade,
    ordre         integer not null default 0,
    unique (epreuve_id)
);

create index if not exists atelier_epreuves_atelier_idx on public.atelier_epreuves (atelier_id);

-- ---------- Droits d'accès (même fonctionnement que les autres tables de l'application) ----------
grant select, insert, update, delete on public.journees         to anon, authenticated;
grant select, insert, update, delete on public.ateliers         to anon, authenticated;
grant select, insert, update, delete on public.atelier_epreuves to anon, authenticated;

-- Les identifiants numériques sont auto-générés : l'application doit pouvoir les utiliser.
grant usage, select on all sequences in schema public to anon, authenticated;

-- Sécurité par lignes (RLS) : on l'active avec des règles permissives pour la clé "anon",
-- ce qui reproduit le comportement des autres tables de l'application (outil interne au club).
alter table public.journees         enable row level security;
alter table public.ateliers         enable row level security;
alter table public.atelier_epreuves enable row level security;

drop policy if exists "pps_all_journees" on public.journees;
create policy "pps_all_journees" on public.journees
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "pps_all_ateliers" on public.ateliers;
create policy "pps_all_ateliers" on public.ateliers
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "pps_all_atelier_epreuves" on public.atelier_epreuves;
create policy "pps_all_atelier_epreuves" on public.atelier_epreuves
    for all to anon, authenticated using (true) with check (true);
