-- ============================================================
-- Schéma PostgreSQL (Supabase) - Championnat France Pompiers Parapente
-- Aligné sur la base Supabase actuelle (export du 26/11/2026).
-- Rejouable : CREATE TABLE IF NOT EXISTS, ALTER ... IF NOT EXISTS,
-- DROP POLICY IF EXISTS avant chaque CREATE POLICY.
--
-- Colonnes de synchronisation (applications PC et mobile) :
--   "uuid"       = identifiant stable partagé entre tous les appareils
--                  (l'id local recommence à 1 sur chaque appareil).
--   "updated_at" = permet de savoir quelle version d'une ligne est la plus récente.
-- ============================================================

-- Utilisateurs de l'application (comptes de connexion)
CREATE TABLE IF NOT EXISTS utilisateurs (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant     VARCHAR(100) NOT NULL UNIQUE,
    mot_de_passe    VARCHAR(256) NOT NULL,   -- haché SHA-256
    role            VARCHAR(40)  NOT NULL,   -- ADMINISTRATEUR, RESPONSABLE_EPREUVE, BENEVOLE, PILOTE, COMITE_PILOTES
    pilote_id       INT NULL,                -- si le compte est lié à un pilote
    actif           BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Pilotes (informations d'inscription au championnat)
CREATE TABLE IF NOT EXISTS pilotes (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_licence      VARCHAR(50) NOT NULL UNIQUE,
    nom                 VARCHAR(100) NOT NULL,
    prenom              VARCHAR(100) NOT NULL,
    departement         VARCHAR(150),
    poids               DOUBLE PRECISION,
    email               VARCHAR(150),
    annee_naissance     INT,
    genre               VARCHAR(50),             -- Homme / Femme
    date_inscription    TIMESTAMPTZ DEFAULT now(),
    uuid                UUID NOT NULL DEFAULT gen_random_uuid(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    numero_pilote       INT,                     -- numéro attribué par l'organisation (facultatif)
    categorie           VARCHAR(10) NOT NULL DEFAULT 'POMPIER'  -- POMPIER ou OPEN
);

-- Épreuves (créées librement par le Responsable de l'épreuve)
CREATE TABLE IF NOT EXISTS epreuves (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                 VARCHAR(150) NOT NULL,
    description         VARCHAR(1000),
    mode_calcul         VARCHAR(20) NOT NULL DEFAULT 'FORMULE', -- FORMULE ou BAREME
    formule             VARCHAR(500),           -- utilisé si mode_calcul = FORMULE
    valeur_cle          VARCHAR(100),           -- utilisé si mode_calcul = BAREME
    sens_classement     VARCHAR(4) DEFAULT 'ASC', -- ASC (plus petit = meilleur) ou DESC (plus grand = meilleur)
    afficher_classement BOOLEAN NOT NULL DEFAULT TRUE,
    compte_dans_general BOOLEAN NOT NULL DEFAULT TRUE,
    actif               BOOLEAN NOT NULL DEFAULT TRUE,
    ordre               INT DEFAULT 0,
    date_creation       TIMESTAMPTZ DEFAULT now(),
    uuid                UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Paramètres/variables saisissables pour chaque épreuve
CREATE TABLE IF NOT EXISTS epreuve_parametres (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    epreuve_id      INT NOT NULL,
    nom_variable    VARCHAR(60) NOT NULL,
    label           VARCHAR(150) NOT NULL,
    unite           VARCHAR(30),
    obligatoire     BOOLEAN DEFAULT TRUE,
    ordre           INT DEFAULT 0,
    uuid            UUID NOT NULL DEFAULT gen_random_uuid(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (epreuve_id) REFERENCES epreuves(id) ON DELETE CASCADE
);

-- Barème de points par rang (utilisé si mode_calcul = BAREME)
CREATE TABLE IF NOT EXISTS bareme_points (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    epreuve_id  INT NOT NULL,
    rang        INT NOT NULL,
    points      DOUBLE PRECISION NOT NULL,
    uuid        UUID NOT NULL DEFAULT gen_random_uuid(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (epreuve_id) REFERENCES epreuves(id) ON DELETE CASCADE,
    UNIQUE (epreuve_id, rang)
);

-- Inscription d'un pilote à une épreuve
CREATE TABLE IF NOT EXISTS inscriptions_epreuve (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pilote_id   INT NOT NULL,
    epreuve_id  INT NOT NULL,
    uuid        UUID NOT NULL DEFAULT gen_random_uuid(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (pilote_id) REFERENCES pilotes(id) ON DELETE CASCADE,
    FOREIGN KEY (epreuve_id) REFERENCES epreuves(id) ON DELETE CASCADE,
    UNIQUE (pilote_id, epreuve_id)
);

-- Résultats saisis (valeurs brutes + points calculés)
CREATE TABLE IF NOT EXISTS resultats (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    epreuve_id      INT NOT NULL,
    pilote_id       INT NOT NULL,
    valeurs_json    VARCHAR(2000),   -- ex: {"temps": 812, "nbrBalises": 6}
    points          DOUBLE PRECISION DEFAULT 0,
    disqualifie     BOOLEAN DEFAULT FALSE,
    saisi_par       VARCHAR(100),
    date_saisie     TIMESTAMPTZ DEFAULT now(),
    uuid            UUID NOT NULL DEFAULT gen_random_uuid(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (epreuve_id) REFERENCES epreuves(id) ON DELETE CASCADE,
    FOREIGN KEY (pilote_id) REFERENCES pilotes(id) ON DELETE CASCADE,
    UNIQUE (epreuve_id, pilote_id)
);

-- ------------------------------------------------------------
-- Planning : journees > ateliers > epreuves
-- Une journée contient des ateliers (matin ou après-midi),
-- un atelier regroupe plusieurs épreuves. Une épreuve n'appartient qu'à UN seul atelier.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS journees (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    nom             TEXT NOT NULL,
    date_journee    DATE,
    ordre           INT NOT NULL DEFAULT 0,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ateliers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    journee_id      BIGINT NOT NULL,
    nom             TEXT NOT NULL,
    creneau         TEXT NOT NULL DEFAULT 'MATIN',   -- MATIN ou APRES_MIDI
    heure_debut     TEXT,                            -- format HH:mm
    heure_fin       TEXT,                            -- format HH:mm
    lieu            TEXT,
    responsable     TEXT,
    ordre           INT NOT NULL DEFAULT 0,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (journee_id) REFERENCES journees(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS atelier_epreuves (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atelier_id      BIGINT NOT NULL,
    epreuve_id      BIGINT NOT NULL UNIQUE,          -- une épreuve dans un seul atelier
    ordre           INT NOT NULL DEFAULT 0,          -- ordre de passage dans l'atelier
    FOREIGN KEY (atelier_id) REFERENCES ateliers(id) ON DELETE CASCADE,
    FOREIGN KEY (epreuve_id) REFERENCES epreuves(id) ON DELETE CASCADE
);

