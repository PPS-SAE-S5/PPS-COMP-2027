-- Migration v5 : planning (journées > ateliers > épreuves)
-- ============================================================
-- À exécuter UNE SEULE FOIS dans Supabase (SQL Editor -> New query -> coller -> Run),
-- sauf si ces trois tables existent déjà (par exemple parce que la version PC a déjà été
-- mise en place avec son propre script v5) : dans ce cas il n'y a RIEN à faire.
--
-- Ce script a été reconstitué à partir des tables et colonnes que lisent/écrivent les versions
-- PC et Android. Grâce à « if not exists », l'exécuter alors que les tables existent ne change rien.
-- ============================================================

create table if not exists public.journees (
    id           integer generated by default as identity primary key,
    uuid         text        not null unique,
    nom          text        not null,
    date_journee date,
    ordre        integer     not null default 0,
    updated_at   timestamptz not null default now()
);

create table if not exists public.ateliers (
    id          integer generated by default as identity primary key,
    uuid        text        not null unique,
    journee_id  integer     not null references public.journees(id) on delete cascade,
    nom         text        not null,
    creneau     text        not null default 'MATIN' check (creneau in ('MATIN', 'APRES_MIDI')),
    heure_debut text,
    heure_fin   text,
    lieu        text,
    responsable text,
    ordre       integer     not null default 0,
    updated_at  timestamptz not null default now()
);

-- Une épreuve ne peut appartenir qu'à UN seul atelier (unique sur epreuve_id)
create table if not exists public.atelier_epreuves (
    id         integer generated by default as identity primary key,
    atelier_id integer not null references public.ateliers(id) on delete cascade,
    epreuve_id integer not null references public.epreuves(id) on delete cascade,
    ordre      integer not null default 0,
    unique (epreuve_id)
);

create index if not exists idx_ateliers_journee on public.ateliers (journee_id);
create index if not exists idx_atelier_epreuves_atelier on public.atelier_epreuves (atelier_id);

-- Accès pour l'application (clé « anon »), comme pour les autres tables du projet
alter table public.journees         enable row level security;
alter table public.ateliers         enable row level security;
alter table public.atelier_epreuves enable row level security;

drop policy if exists "pps_tout_journees" on public.journees;
create policy "pps_tout_journees" on public.journees
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "pps_tout_ateliers" on public.ateliers;
create policy "pps_tout_ateliers" on public.ateliers
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "pps_tout_atelier_epreuves" on public.atelier_epreuves;
create policy "pps_tout_atelier_epreuves" on public.atelier_epreuves
    for all to anon, authenticated using (true) with check (true);

grant select, insert, update, delete on public.journees         to anon, authenticated;
grant select, insert, update, delete on public.ateliers         to anon, authenticated;
grant select, insert, update, delete on public.atelier_epreuves to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
